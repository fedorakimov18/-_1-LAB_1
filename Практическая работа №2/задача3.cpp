// Задача 3. Убрать условный оператор "Если" из блока:
//     Если (A = 0) Тогда
//         B = 2;
//     Иначе
//         B = 1;
//     КонецЕсли;
// A может принимать значение 0 или 1.
//
// Так как A равно только 0 или 1, нужные пары значений
// (A = 0 -> B = 2) и (A = 1 -> B = 1) даёт формула B = 2 - A.

#include <iostream>

using namespace std;

int main() {
    int A;

    cout << "Введите A (0 или 1): ";
    cin >> A;

    int B = 2 - A;  // условный оператор не нужен

    cout << "B = " << B << endl;

    return 0;
}
