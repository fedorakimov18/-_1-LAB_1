// Задача 1. Поменять местами значения двух переменных a и b
// без объявления других переменных.
// Разрешены только присваивание и арифметические операции.

#include <iostream>

using namespace std;

int main() {
    int a, b;

    cout << "Введите a: ";
    cin >> a;
    cout << "Введите b: ";
    cin >> b;

    cout << "До обмена:    a = " << a << ", b = " << b << endl;

    // Обмен через сумму: третья переменная не нужна
    a = a + b;  // в a лежит сумма старых a и b
    b = a - b;  // из суммы вычли старое b - получили старое a
    a = a - b;  // из суммы вычли новое b (старое a) - получили старое b

    cout << "После обмена: a = " << a << ", b = " << b << endl;

    return 0;
}
